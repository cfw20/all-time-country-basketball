/** name|pos|ht|year|nat|role|deal|arch|ovr|usg|3rate|start|pos2 */
type Row = (string | number)[];

function block(rows: Row[]): string {
  if (rows.length !== 22) throw new Error(`house roster is ${rows.length}`);
  return `\n${rows.map((row) => row.join("|")).join("\n")}\n`;
}

const US = "United States";

